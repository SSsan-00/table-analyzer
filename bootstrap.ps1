function Initialize-Source {
    $srcRoot = Join-Path $PSScriptRoot "src"
    if ((Test-Path $srcRoot) -and -not $Force) {
        Write-Host "src already exists. Skipping init. Use -Force to replace it."
        return
    }

    if ((Test-Path $srcRoot) -and $Force) {
        Remove-Item $srcRoot -Recurse -Force
    }

    $zipPath = Join-Path ([System.IO.Path]::GetTempPath()) ("table-analyzer-src-" + [System.Guid]::NewGuid().ToString("N") + ".zip")
    [System.IO.File]::WriteAllBytes($zipPath, [System.Convert]::FromBase64String(($ArchiveBase64 -replace "\s", "")))
    Expand-Archive -Path $zipPath -DestinationPath $PSScriptRoot -Force:$Force
    Remove-Item $zipPath -Force
    Write-Host "Source expanded under: $srcRoot"
}

function Build-Tool {
    $cliProject = Join-Path $PSScriptRoot "src/TableAnalyzer.Cli/TableAnalyzer.Cli.csproj"
    $guiProject = Join-Path $PSScriptRoot "src/TableAnalyzer.Gui/TableAnalyzer.Gui.csproj"
    if (-not (Test-Path $cliProject)) {
        Initialize-Source
    }

    & dotnet build $cliProject -c Release
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet build failed for CLI."
    }

    & dotnet build $guiProject -c Release
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet build failed for GUI."
    }
}

function Publish-Tool {
    $cliProject = Join-Path $PSScriptRoot "src/TableAnalyzer.Cli/TableAnalyzer.Cli.csproj"
    $guiProject = Join-Path $PSScriptRoot "src/TableAnalyzer.Gui/TableAnalyzer.Gui.csproj"
    if (-not (Test-Path $cliProject)) {
        Initialize-Source
    }

    $publishRoot = Join-Path $PSScriptRoot "publish"
    $cliOutput = Join-Path $publishRoot ("TableAnalyzer.Cli/" + $Runtime)
    $guiOutput = Join-Path $publishRoot ("TableAnalyzer.Gui/" + $Runtime)

    foreach ($output in @($cliOutput, $guiOutput)) {
        if (Test-Path $output) {
            Remove-Item $output -Recurse -Force
        }

        New-Item -ItemType Directory -Path $output -Force | Out-Null
    }

    & dotnet publish $cliProject -c Release -r $Runtime --self-contained true -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -p:EnableCompressionInSingleFile=true -p:DebugType=none -p:DebugSymbols=false -o $cliOutput
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet publish failed for CLI."
    }

    & dotnet publish $guiProject -c Release -r $Runtime --self-contained true -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -p:EnableCompressionInSingleFile=true -p:DebugType=none -p:DebugSymbols=false -o $guiOutput
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet publish failed for GUI."
    }

    $cliExe = Join-Path $cliOutput "TableAnalyzer.Cli.exe"
    $guiExe = Join-Path $guiOutput "TableAnalyzer.Gui.exe"
    if (-not (Test-Path $cliExe)) {
        throw "CLI single-file exe was not created: $cliExe"
    }
    if (-not (Test-Path $guiExe)) {
        throw "GUI single-file exe was not created: $guiExe"
    }

    Write-Host "CLI exe: $cliExe"
    Write-Host "GUI exe: $guiExe"
}

function Invoke-Analysis {
    if ([string]::IsNullOrWhiteSpace($Out)) {
        throw "analyze requires -Out."
    }

    $dll = Join-Path $PSScriptRoot "src/TableAnalyzer.Cli/bin/Release/net9.0/TableAnalyzer.Cli.dll"
    if (-not (Test-Path $dll)) {
        Build-Tool
    }

    $arguments = @("analyze")
    if (-not [string]::IsNullOrWhiteSpace($ProjectFolder) -or
        -not [string]::IsNullOrWhiteSpace($AnalysisFolder) -or
        -not [string]::IsNullOrWhiteSpace($AnalysisFile)) {
        if ([string]::IsNullOrWhiteSpace($ProjectFolder)) {
            throw "analyze requires -ProjectFolder when project mode options are used."
        }
        if ([string]::IsNullOrWhiteSpace($AnalysisFolder)) {
            throw "analyze requires -AnalysisFolder when project mode options are used."
        }

        $arguments += @("--project-folder", $ProjectFolder, "--analysis-folder", $AnalysisFolder)
        if (-not [string]::IsNullOrWhiteSpace($AnalysisFile)) {
            $arguments += @("--analysis-file", $AnalysisFile)
        }
    }
    else {
        if ([string]::IsNullOrWhiteSpace($Input)) {
            throw "analyze requires -Input or -ProjectFolder/-AnalysisFolder."
        }

        $arguments += @("--input", $Input)
    }

    $arguments += @("--out", $Out, "--format", $Format, "--analysis-scope", $AnalysisScope)
    & dotnet $dll @arguments
    if ($LASTEXITCODE -ne 0) {
        throw "TableAnalyzer analyze failed."
    }
}

function Start-Gui {
    $dll = Join-Path $PSScriptRoot "src/TableAnalyzer.Gui/bin/Release/net9.0-windows/TableAnalyzer.Gui.dll"
    if (-not (Test-Path $dll)) {
        Build-Tool
    }

    & dotnet $dll
    if ($LASTEXITCODE -ne 0) {
        throw "TableAnalyzer GUI failed."
    }
}

switch ($Command) {
    "init" { Initialize-Source }
    "build" { Build-Tool }
    "publish" { Publish-Tool }
    "analyze" { Invoke-Analysis }
    "run" { Invoke-Analysis }
    "gui" { Start-Gui }
    "all" {
        Initialize-Source
        Build-Tool
        if (-not [string]::IsNullOrWhiteSpace($Input) -or
            -not [string]::IsNullOrWhiteSpace($ProjectFolder) -or
            -not [string]::IsNullOrWhiteSpace($AnalysisFolder) -or
            -not [string]::IsNullOrWhiteSpace($AnalysisFile) -or
            -not [string]::IsNullOrWhiteSpace($Out)) {
            Invoke-Analysis
        }
    }
}
